// Generates src/styles/_icons.scss with only the Phosphor icons referenced in src/.
// Runs automatically before start/build/test (see package.json "pre*" scripts).
// Usage: node scripts/build-icons.mjs [--check]   (--check exits 1 if the file is stale)
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const srcDir = join(root, 'src');
const outFile = join(srcDir, 'styles', '_icons.scss');
const phosphorCss = join(
  root,
  'node_modules',
  '@phosphor-icons',
  'web',
  'src',
  'regular',
  'style.css',
);

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const used = new Set();
for (const file of walk(srcDir)) {
  if (!['.ts', '.html'].includes(extname(file)) || file.endsWith('.spec.ts')) continue;
  for (const m of readFileSync(file, 'utf8').matchAll(/\bph-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g))
    used.add(m[1]);
}

const css = readFileSync(phosphorCss, 'utf8');
const glyphs = new Map(
  [...css.matchAll(/\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"([^"]+)";/g)].map((m) => [
    m[1],
    m[2],
  ]),
);

const missing = [...used].filter((n) => !glyphs.has(n)).sort();
if (missing.length) {
  console.error(`Unknown Phosphor icon(s): ${missing.join(', ')}`);
  process.exit(1);
}

const fontPath = '../../node_modules/@phosphor-icons/web/src/regular';
const rules = [...used]
  .sort()
  .map((n) => `.ph.ph-${n}::before {\n  content: '${glyphs.get(n)}';\n}`)
  .join('\n');

const out = `// GENERATED by scripts/build-icons.mjs — do not edit. ${used.size} icons.
@font-face {
  font-family: 'Phosphor';
  src:
    url('${fontPath}/Phosphor.woff2') format('woff2'),
    url('${fontPath}/Phosphor.woff') format('woff');
  font-weight: normal;
  font-style: normal;
  font-display: block;
}

.ph {
  font-family: 'Phosphor' !important;
  speak: never;
  font-style: normal;
  font-weight: normal;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  letter-spacing: 0;
  display: inline-block;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${rules}
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== out) {
    console.error('src/styles/_icons.scss is stale. Run: npm run icons');
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(outFile, out);
console.log(`icons: ${used.size} Phosphor icons -> src/styles/_icons.scss`);
